interface LanguageContextValue {
  language: LanguageId;
  setLanguage: Dispatch<SetStateAction<LanguageId>>;
  t: (text: string, values?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const STORAGE_KEY = "lesson-generator-language";

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<LanguageId>(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return isLanguageId(stored) ? stored : "en";
  });

  useLayoutEffect(() => {
    document.documentElement.lang =
      LANGUAGE_OPTIONS.find((option) => option.id === language)?.locale ?? "en-IN";
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (text: string, values: Record<string, string | number> = {}) =>
        translateText(text, language, values),
    }),
    [language],
  );
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}

export function translateText(
  text: string,
  language: LanguageId,
  values: Record<string, string | number> = {},
) {
  const template = language === "en" ? text : translations[language][text] ?? text;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}

function isLanguageId(value: string | null): value is LanguageId {
  return value !== null && LANGUAGE_OPTIONS.some((option) => option.id === value);
}
